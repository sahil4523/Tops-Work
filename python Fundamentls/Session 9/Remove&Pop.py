my_fav_apps=["Instagram", "WhatsApp", "Zomato", "Spotify", "YouTube", "Google Maps"]

my_fav_apps.remove("Zomato")
print("After remove:", my_fav_apps)

my_fav_apps.pop()
print("After pop:", my_fav_apps)

#"remove() removes a specific value from the list."

# "pop() removes the last item by default."